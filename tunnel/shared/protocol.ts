/**
 * Localians tunnel protocol (v1)
 *
 * 1. The CLI opens an outbound HTTP(S) connection to the gateway's tunnel host and sends
 *      GET /v1/connect
 *      Upgrade: localians-tunnel/1
 *      Authorization: Bearer <connect token issued by the control plane>
 * 2. The gateway answers `101 Switching Protocols`. From then on the socket carries
 *    HTTP/2 (RFC 9113) with the roles reversed: the gateway is the HTTP/2 *client*
 *    and the CLI is the HTTP/2 *server*. Each public request becomes one HTTP/2 stream,
 *    which gives multiplexing, flow control (backpressure) and per-request cancellation
 *    from a standard protocol rather than a bespoke framing format.
 * 3. WebSocket upgrades are sent as a stream flagged with `x-localians-upgrade`; once the
 *    local server returns 101 the stream carries raw bytes in both directions.
 *
 * Confidentiality comes from TLS on the outer connection (no custom cryptography).
 */

export const PROTOCOL_UPGRADE = "localians-tunnel/1";
export const CONNECT_PATH = "/v1/connect";

/** Request headers the gateway adds on each forwarded stream. */
export const H = {
  originalHost: "x-localians-original-host",
  upgrade: "x-localians-upgrade",
  upstreamStatus: "x-localians-upstream-status",
  error: "x-localians-error",
} as const;

/** Values the CLI puts in `x-localians-error` so the gateway can render a useful page. */
export type TunnelErrorCode = "local-unreachable" | "local-timeout" | "local-error";

/** Preview labels: lowercase base32-ish, generated by the control plane. */
export const LABEL_PATTERN = /^[a-z2-7]{12}$/;

export const CONNECT_TOKEN_ISSUER = "localians-control-plane";
export const CONNECT_TOKEN_AUDIENCE = "localians-gateway";

export type ConnectTokenClaims = {
  /** Tunnel session id. */
  sid: string;
  /** User id. */
  sub: string;
  /** CLI credential id. */
  cid: string;
  /** Preview label the session owns. */
  label: string;
  /** Local port (informational). */
  port: number;
};

/**
 * Traffic counters for one physical connection, **cumulative since that connection was
 * accepted** (monotonic). The control plane stores the last values it applied per
 * `connectionId` and adds only the increase, so a retried or redelivered report is
 * never counted twice.
 *
 * - `requests`: HTTP requests forwarded to the CLI, plus one per WebSocket upgrade.
 * - `bytesIn`: request-body and visitor→app WebSocket bytes.
 * - `bytesOut`: response-body and app→visitor WebSocket bytes.
 * Headers, TLS and HTTP/2 framing are not counted.
 */
export type ConnectionCounters = { bytesIn: number; bytesOut: number; requests: number };

/** Gateway → control plane event payloads (POST /api/internal/gateway/events). */
export type GatewayEvent =
  | { type: "connected"; sessionId: string; connectionId: string }
  | ({ type: "heartbeat"; sessionId: string; connectionId: string } & ConnectionCounters)
  | ({ type: "disconnected"; sessionId: string; connectionId: string; reason: string } & ConnectionCounters);

export type GatewayEventsRequest = { gatewayId: string; events: GatewayEvent[] };

/**
 * Who may open a preview. The gateway enforces it on every HTTP request and WebSocket upgrade.
 * `version` changes whenever the password changes or visitors are signed out, which
 * invalidates every visitor access cookie issued before.
 * `expiresAt` (epoch ms) is when the session's time runs out: the gateway stops serving at that moment and closes the
 * tunnel, without waiting for the control plane. Absent from older control planes (they end sessions at a heartbeat).
 */
export type AccessPolicy = { mode: "public" | "password"; version: number; ttlS: number; expiresAt?: number };

/** Verdicts carry the current policy, so a missed policy push is corrected at the next heartbeat. */
export type GatewayEventsResponse = { sessions: Record<string, { action: "continue" | "terminate"; reason?: string; policy?: AccessPolicy }> };

/** Gateway → control plane: a visitor submitted a preview password (POST /api/internal/gateway/access). */
export type AccessCheckRequest = { sessionId: string; password: string; clientIp: string };
export type AccessCheckResponse =
  | { ok: true; policy: AccessPolicy }
  | { ok: false; error: "invalid_password" | "rate_limited" | "not_protected" | "ended"; retryAfterS?: number; policy?: AccessPolicy };

/** Reserved paths on preview hosts, handled by the gateway itself (never forwarded). */
export const ACCESS_PATHS = { login: "/__localians/access", logout: "/__localians/logout" } as const;
/** Visitor access cookie. The `localians.` prefix means it's stripped before requests reach the app. */
export const ACCESS_COOKIE = "localians.preview_access";

/**
 * Control plane → gateway control API. Served on the gateway's private admin listener
 * (loopback by default), authenticated with the same GATEWAY_API_SECRET bearer.
 *   GET  /v1/tunnels                       → GatewayTunnelsResponse
 *   POST /v1/sessions/<sessionId>/terminate → GatewayTerminateResponse
 *   POST /v1/sessions/<sessionId>/policy    (AccessPolicy body) → { applied: number }
 */
export type GatewayTunnelsResponse = { gatewayId: string; tunnels: { sessionId: string; connectionId: string; connectedAt: string }[] };
export type GatewayTerminateResponse = { gatewayId: string; terminated: number; routing: boolean };
